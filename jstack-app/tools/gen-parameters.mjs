/**
 * PARAMETERS.md generator (L-1, ADR-41, LK-02).
 *
 * Josh asked for a registry "easy for the EA agent to change (awareness, docs
 * and simple process)". This file is the awareness half: one page listing
 * every tunable, its default, its range, where it is read, how Josh changes
 * it and how the EA asks. Generated from `data/parameters.ts`, so it cannot
 * drift from the table the app enforces — `tests/unit/codemap.test.ts`
 * regenerates it and fails if the committed file differs.
 *
 * It reads the TypeScript source rather than importing it: this is a plain
 * `.mjs` run by `pnpm codemap` with no transpiler in front of it, and the
 * alternative — a second copy of the table in JSON — is the copy that drifts.
 * The parse is deliberately narrow and throws on anything it does not
 * recognise, because a generator that silently emits a shorter table is
 * exactly the failure this page exists to prevent.
 *
 * Run: node tools/gen-parameters.mjs [--out <path>]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const APP_ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const outFlag = process.argv.indexOf("--out");
const OUT = outFlag === -1 ? join(APP_ROOT, "PARAMETERS.md") : process.argv[outFlag + 1];

const source = readFileSync(join(APP_ROOT, "data", "parameters.ts"), "utf8");
const table = source.slice(source.indexOf("const TABLE = ["), source.indexOf("] as const satisfies"));

/** one `{ ... }` object literal per row, split on the entry key each starts with */
const rows = table
  .split(/\n\s*\{\n/)
  .slice(1)
  .map((chunk) => {
    const field = (name) => {
      const m = new RegExp(`\\b${name}:\\s*("(?:[^"\\\\]|\\\\.)*"|true|false|-?\\d+|\\[[^\\]]*\\])`).exec(chunk);
      return m == null ? undefined : m[1];
    };
    const unquote = (v) => (v == null ? undefined : v.startsWith('"') ? JSON.parse(v) : v);
    const list = (v) =>
      v == null || v === "[]"
        ? []
        : v
            .slice(1, -1)
            .split(",")
            .map((s) => unquote(s.trim()))
            .filter((s) => s !== undefined && s !== "");
    const row = {
      key: unquote(field("key")),
      label: unquote(field("label")),
      help: unquote(field("help")),
      unit: unquote(field("unit")),
      default: field("default"),
      min: field("min"),
      max: field("max"),
      usedBy: list(field("usedBy")),
      plannedFor: unquote(field("plannedFor")),
      changeable: unquote(field("changeable")),
    };
    if (row.key == null || row.label == null || row.unit == null || row.default == null) {
      throw new Error(`gen-parameters: could not read a row from data/parameters.ts — ${chunk.slice(0, 80)}`);
    }
    return row;
  });

if (rows.length === 0) throw new Error("gen-parameters: no rows parsed from data/parameters.ts");

// "10 – 200 count" is not English; a count's unit is the thing being counted,
// and the label already says what that is.
const range = (r) => (r.unit === "boolean" ? "on / off" : r.unit === "count" ? `${r.min} – ${r.max}` : `${r.min} – ${r.max} ${r.unit}`);
const usedBy = (r) => (r.usedBy.length > 0 ? r.usedBy.map((f) => `\`${f}\``).join(", ") : `— not read yet (${r.plannedFor})`);
const asks = (r) =>
  r.changeable === "josh-or-ea-proposal"
    ? `\`POST /parameters/propose { key, value, reason }\` → a decision card on Needs you`
    : "— Josh only";

const lines = [
  "# PARAMETERS.md — every tunable in JSTACK",
  "",
  "**Generated by `tools/gen-parameters.mjs` on every `pnpm codemap`. Do not edit.**",
  "The table it reads is `jstack-app/data/parameters.ts`; the values live on the server",
  "(`GET /parameters`), and the range published here is the range the server enforces —",
  "a `PUT` outside it is a `422 { field: \"value\" }`.",
  "",
  "**Josh changes a value** in Settings › Security, which renders one control per row below.",
  "**The EA never writes one.** It raises a card with `POST /parameters/propose`, and",
  "approving that card is what applies the value — with the same ten-second undo as every",
  "other decision. Answering Never records the refusal so the EA can read it and stop asking.",
  "",
  "| Key | What it does | Default | Range | Read by | The EA asks with |",
  "|---|---|---|---|---|---|",
  ...rows.map((r) => `| \`${r.key}\` | **${r.label}** — ${r.help} | \`${r.default}\` | ${range(r)} | ${usedBy(r)} | ${asks(r)} |`),
  "",
  "## Adding one",
  "",
  "1. A row in `jstack-app/data/parameters.ts` (the key joins `ParameterKey` in `data/types.ts`;",
  "   `pnpm check` fails until it has a row).",
  "2. Nothing else. The handler validates from the row, Settings › Security renders from the row,",
  "   and this page regenerates from the row.",
  "3. Read it with `currentParameter(\"your.key\")` from `stores/parameters.ts`, and add that file",
  "   to the row's `usedBy` — `tests/unit/parameters.test.ts` opens it and checks the key is there.",
  "",
];

writeFileSync(OUT, lines.join("\n"), "utf8");
console.log(`PARAMETERS.md written: ${rows.length} parameters`);
